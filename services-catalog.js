window.getServiceCategoryLabel = function(cat) {
  const map = {
    incorporation: 'Incorporation',
    tax: 'Income Tax & Compliance',
    ip: 'Trademark & IP',
    licenses: 'Licenses',
    fundraising: 'Fundraising & Grants',
    digital: 'Digital',
    conversion: 'Business Closure & Conversion',
    other: 'Other & Advisory'
  };
  return map[cat] || (cat ? cat.toUpperCase() : 'Business Services');
};

/**
 * Initializes a clean, two-step cascading service picker with live search.
 * Completely eliminates dropdown scrolling fatigue and information overload.
 */
window.initServicePicker = function(cfg) {
  const catEl = document.getElementById(cfg.categorySelectId);
  const searchEl = document.getElementById(cfg.searchInputId);
  const serviceEl = document.getElementById(cfg.serviceSelectId);
  const countEl = cfg.countBadgeId ? document.getElementById(cfg.countBadgeId) : null;
  if (!serviceEl) return null;

  const catalog = window.ALL_SERVICES_CATALOG || [];

  function populate(targetValue) {
    const selectedCat = catEl ? catEl.value : 'all';
    const query = searchEl ? searchEl.value.trim().toLowerCase() : '';

    let matches = catalog;

    if (query) {
      matches = catalog.filter(s => {
        const titleMatch = s.title.toLowerCase().includes(query);
        const catLabel = (window.getServiceCategoryLabel(s.cat) || '').toLowerCase();
        return titleMatch || catLabel.includes(query);
      });
    } else if (selectedCat && selectedCat !== 'all') {
      matches = catalog.filter(s => s.cat === selectedCat);
    }

    serviceEl.innerHTML = '';

    if (cfg.allowEmptyOption) {
      const emptyOpt = document.createElement('option');
      emptyOpt.value = '';
      emptyOpt.textContent = cfg.emptyLabel || '-- None (Just Create Client Account) --';
      if (!targetValue) emptyOpt.selected = true;
      serviceEl.appendChild(emptyOpt);
    }

    if (matches.length === 0 && selectedCat !== 'other') {
      const noneOpt = document.createElement('option');
      noneOpt.value = '';
      noneOpt.disabled = true;
      noneOpt.selected = true;
      noneOpt.textContent = '-- No matching services found --';
      serviceEl.appendChild(noneOpt);
    } else if (!query && selectedCat === 'all') {
      const grouped = {};
      matches.forEach(s => {
        if (!grouped[s.cat]) grouped[s.cat] = [];
        grouped[s.cat].push(s);
      });
      for (const c in grouped) {
        const og = document.createElement('optgroup');
        og.label = window.getServiceCategoryLabel(c);
        grouped[c].forEach(s => {
          const opt = document.createElement('option');
          opt.value = s.title;
          opt.textContent = s.title;
          if (targetValue && s.title.toLowerCase() === targetValue.toLowerCase()) {
            opt.selected = true;
          }
          og.appendChild(opt);
        });
        serviceEl.appendChild(og);
      }
    } else {
      matches.forEach((s, idx) => {
        const opt = document.createElement('option');
        opt.value = s.title;
        opt.textContent = s.title;
        if (targetValue) {
          if (s.title.toLowerCase() === targetValue.toLowerCase()) opt.selected = true;
        } else if (!cfg.allowEmptyOption && idx === 0) {
          opt.selected = true;
        }
        serviceEl.appendChild(opt);
      });
    }

    // Always include Custom / Advisory at bottom if in "other" or searching
    if (selectedCat === 'other' || (query && ('custom service'.includes(query) || 'fundraising'.includes(query)))) {
      const advOpt = document.createElement('option');
      advOpt.value = 'Fundraising Advisory';
      advOpt.textContent = 'Fundraising Advisory';
      if (targetValue && targetValue.toLowerCase().includes('fundrais')) advOpt.selected = true;
      serviceEl.appendChild(advOpt);

      const custOpt = document.createElement('option');
      custOpt.value = 'Other Custom Compliance Service';
      custOpt.textContent = 'Other Custom Compliance Service';
      if (targetValue && targetValue.toLowerCase().includes('custom')) custOpt.selected = true;
      serviceEl.appendChild(custOpt);
    }

    if (countEl) {
      if (query) {
        countEl.textContent = matches.length + ' matching';
      } else if (selectedCat === 'all') {
        countEl.textContent = catalog.length + ' services';
      } else {
        countEl.textContent = matches.length + ' available';
      }
    }
  }

  if (catEl) {
    catEl.addEventListener('change', () => {
      if (searchEl) searchEl.value = '';
      populate();
    });
  }

  if (searchEl) {
    searchEl.addEventListener('input', () => {
      populate();
    });
  }

  // Initial population
  populate(cfg.initialValue);

  return {
    setService: function(serviceName) {
      if (!serviceName) {
        if (catEl) catEl.value = cfg.defaultCategory || (cfg.allowEmptyOption ? 'all' : 'incorporation');
        if (searchEl) searchEl.value = '';
        populate();
        return;
      }
      const item = catalog.find(s => s.title.toLowerCase() === serviceName.toLowerCase() || s.title.toLowerCase().includes(serviceName.toLowerCase()));
      if (item) {
        if (catEl) catEl.value = item.cat;
        if (searchEl) searchEl.value = '';
        populate(item.title);
      } else {
        if (catEl) catEl.value = 'other';
        if (searchEl) searchEl.value = '';
        populate(serviceName);
      }
    },
    reset: function() {
      if (catEl) catEl.value = cfg.defaultCategory || (cfg.allowEmptyOption ? 'all' : 'incorporation');
      if (searchEl) searchEl.value = '';
      populate();
    },
    refresh: populate
  };
};
